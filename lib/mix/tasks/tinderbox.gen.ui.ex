defmodule Mix.Tasks.Tinderbox.Gen.Ui do
  @shortdoc "Installs the themepack UI kit (components, app shell, /dev/ui gallery) into a Phoenix project"

  @moduledoc """
  Installs the themepack UI kit into a Phoenix LiveView project generated by
  `phx.new` (with its default Tailwind + daisyUI assets).

  ```sh
  mix tinderbox.gen.ui --themepack slate
  ```

  A themepack is a light and a dark daisyUI theme, a radius/density scale, font
  stacks and an app shell:

  | Pack | Shell | Look |
  |---|---|---|
  | `ember` (default) | sidebar | Warm orange on charcoal, medium density |
  | `slate` | sidebar | Neutral grays with indigo, compact |
  | `harbor` | top navigation | Blue and white, roomy |

  Every pack shares one component kit, `<App>Web.UI`, which `html_helpers/0`
  brings into every template: page headers, cards, stats, badges, alerts,
  tabs, modals, dropdowns, avatars, feeds, forms sections, a searchable,
  sortable, paginated data table and the app shell. Browse them at
  `/dev/ui` (dev only). Phoenix's demo layout is replaced with one that uses
  the app shell; a customized layout is left alone.

  Re-run with another `--themepack` to switch: only the themepack region of
  `assets/css/app.css` and the `<App>Web.UI` config change. Without
  `--themepack`, the installed pack is kept.
  """

  use Igniter.Mix.Task

  @impl Igniter.Mix.Task
  def info(_argv, _source) do
    %Igniter.Mix.Task.Info{
      group: :tinderbox,
      example: "mix tinderbox.gen.ui --themepack slate",
      schema: [themepack: :string]
    }
  end

  @impl Igniter.Mix.Task
  def igniter(igniter) do
    Tinderbox.Gen.Ui.apply(igniter, igniter.args.options)
  end
end
