defmodule Tinderbox.Gen.Ui do
  @moduledoc """
  Installs the themepack UI kit into a Phoenix LiveView project (one generated by
  `phx.new` with its Tailwind + daisyUI assets):

    * the themepack region of `assets/css/app.css`: a light and a dark daisyUI
      theme and the font stacks of the chosen `Tinderbox.Themepack`, replacing
      Phoenix's two stock themes,
    * `config :<app>, <App>Web.UI, themepack: …, shell: :sidebar | :topnav`,
      which `<App>Web.UI.Shell` reads at compile time,
    * the kit, written once and then owned by the project: `<App>Web.UI`
      (`use`d by `html_helpers/0` next to CoreComponents), `.Components`,
      `.Shell`, `.DataTable`, `.ListState`, and its test,
    * `<App>Web.UIGalleryLive` at `/dev/ui`, inside Phoenix's dev-only scope,
    * with `apply/2` only, `<App>Web.Layouts` wrapped in the app shell, when it
      is still Phoenix's demo layout.

  Every step is idempotent, so re-running with another `--themepack` only
  rewrites the themepack region and the config. Without `--themepack` the
  installed pack is kept (`Tinderbox.Themepack.default/0` on a first run).
  """

  alias Tinderbox.Gen
  alias Tinderbox.Gen.Saas.Edits
  alias Tinderbox.Themepack

  @css "assets/css/app.css"

  @main_plugin ~r/@plugin "([^"]*daisyui)"/
  @region ~r{/\* tinderbox:themepack \w+.*?/\* tinderbox:themepack:end \*/\n?}s
  @installed ~r{/\* tinderbox:themepack (\w+)}
  @stock_comment ~r{/\* daisyUI theme plugin\..*?\*/\n}s
  @theme_block ~r/@plugin "[^"]*daisyui-theme" \{[^}]*\}\n?/
  @main_block ~r/@plugin "[^"]*daisyui"(?: \{[^}]*\})?;?\n/

  @kit [
    {"UI", "ui/ui.ex.eex"},
    {"UI.Components", "ui/components.ex.eex"},
    {"UI.Shell", "ui/shell.ex.eex"},
    {"UI.DataTable", "ui/data_table.ex.eex"},
    {"UI.ListState", "ui/list_state.ex.eex"},
    {"UIGalleryLive", "ui/ui_gallery_live.ex.eex"}
  ]

  @doc "Installs the kit and wraps Phoenix's demo layout in the app shell."
  @spec apply(Igniter.t(), keyword()) :: Igniter.t()
  def apply(igniter, opts) do
    {igniter, assigns} = prepare(igniter, opts)

    igniter
    |> install(assigns)
    |> replace_layout(assigns)
  end

  @doc """
  Everything `apply/2` does except the layout: for stacks (SaaS) that write
  their own layout on top of the kit.
  """
  @spec install_kit(Igniter.t(), keyword()) :: Igniter.t()
  def install_kit(igniter, opts) do
    {igniter, assigns} = prepare(igniter, opts)
    install(igniter, assigns)
  end

  defp prepare(igniter, opts) do
    igniter = require_phoenix!(igniter)
    css = require_assets!(igniter)
    {igniter, router} = Igniter.Libs.Phoenix.select_router(igniter)

    {igniter,
     [
       app: Igniter.Project.Application.app_name(igniter),
       prefix: Igniter.Project.Module.module_name_prefix(igniter),
       web: Igniter.Libs.Phoenix.web_module(igniter),
       router: router,
       themepack: Themepack.fetch!(opts[:themepack] || installed(css) || Themepack.default()),
       theme_plugin: theme_plugin(css)
     ]}
  end

  defp install(igniter, assigns) do
    pack = assigns[:themepack]

    igniter
    |> write_themepack(assigns)
    |> configure(assigns)
    |> create_kit(assigns)
    |> import_kit(assigns)
    |> add_gallery_route(assigns)
    |> create_list_state_test(assigns)
    |> Igniter.add_notice(
      "Themepack #{pack.label} (#{pack.shell} shell) applied. Switch with " <>
        "`mix tinderbox.gen.ui --themepack <#{Enum.join(Themepack.names(), "|")}>`; " <>
        "see every component at http://localhost:4000/dev/ui (dev only)."
    )
  end

  # -- preconditions ---------------------------------------------------------

  defp require_phoenix!(igniter) do
    case Igniter.Libs.Phoenix.list_routers(igniter) do
      {_igniter, []} ->
        Mix.raise(
          "tinderbox.gen.ui needs a Phoenix project. Generate one with: " <>
            "mix igniter.new my_app --with phx.new"
        )

      {igniter, _routers} ->
        igniter
    end
  end

  # Returns the stylesheet: the pack and the plugin specifier are read from it.
  defp require_assets!(igniter) do
    css =
      if Igniter.exists?(igniter, @css) do
        igniter
        |> Igniter.include_existing_file(@css)
        |> Map.fetch!(:rewrite)
        |> Rewrite.source!(@css)
        |> Rewrite.Source.get(:content)
      end

    if is_nil(css) or not Regex.match?(@main_plugin, css) do
      Mix.raise(
        "tinderbox.gen.ui needs Phoenix's Tailwind + daisyUI assets (assets/css/app.css), " <>
          "which mix phx.new generates unless --no-assets is given."
      )
    end

    css
  end

  defp installed(css) do
    case Regex.run(@installed, css, capture: :all_but_first) do
      [name] -> name
      nil -> nil
    end
  end

  # Phoenix 1.8 bundles daisyUI (`daisyui/packages/bundle/daisyui`), earlier
  # projects vendor it (`../vendor/daisyui`); the theme plugin sits beside it.
  defp theme_plugin(css) do
    [_, main] = Regex.run(@main_plugin, css)
    main <> "-theme"
  end

  # -- stylesheet and config -------------------------------------------------

  defp write_themepack(igniter, assigns) do
    region = Gen.render_template("ui/themepacks/#{assigns[:themepack].name}.css.eex", assigns)

    Gen.update_file(igniter, @css, fn css ->
      if Regex.match?(@region, css) do
        {:ok, Regex.replace(@region, css, fn _ -> region end, global: false)}
      else
        {:ok, replace_stock_themes(css, region)}
      end
    end)
  end

  # Phoenix ships a commented light and dark theme; the first becomes the
  # region, the rest go. Without any, the region follows the daisyUI plugin.
  defp replace_stock_themes(css, region) do
    css = Regex.replace(@stock_comment, css, "", global: false)

    css =
      case Regex.run(@theme_block, css, return: :index) do
        [{start, length}] ->
          {head, tail} = String.split_at(css, start)
          {_block, tail} = String.split_at(tail, length)
          head <> region <> Regex.replace(@theme_block, tail, "")

        nil ->
          Regex.replace(@main_block, css, fn block -> block <> "\n" <> region end, global: false)
      end

    Regex.replace(~r/\n{3,}/, css, "\n\n")
  end

  defp configure(igniter, assigns) do
    ui = Module.concat(assigns[:web], "UI")
    pack = assigns[:themepack]

    igniter
    |> Igniter.Project.Config.configure("config.exs", assigns[:app], [ui, :themepack], pack.name)
    |> Igniter.Project.Config.configure("config.exs", assigns[:app], [ui, :shell], pack.shell)
  end

  # -- the kit ---------------------------------------------------------------

  # Written once: after the first run the kit is the project's own code.
  defp create_kit(igniter, assigns) do
    Enum.reduce(@kit, igniter, fn {suffix, template}, igniter ->
      module = Module.concat(assigns[:web], suffix)

      case Igniter.Project.Module.module_exists(igniter, module) do
        {true, igniter} ->
          igniter

        {false, igniter} ->
          Igniter.Project.Module.create_module(
            igniter,
            module,
            Gen.render_template(template, assigns)
          )
      end
    end)
  end

  # Next to CoreComponents in `html_helpers/0`, so every LiveView, component
  # and controller template sees the kit.
  defp import_kit(igniter, assigns) do
    web = inspect(assigns[:web])

    case Igniter.Project.Module.find_module(igniter, assigns[:web]) do
      {:ok, {igniter, source, _zipper}} ->
        Gen.update_file(igniter, source.path, fn content ->
          core = ~r/^([ \t]*)import #{Regex.escape(web)}\.CoreComponents\n/m

          cond do
            String.contains?(content, "use #{web}.UI\n") ->
              {:ok, content}

            Regex.match?(core, content) ->
              {:ok, Regex.replace(core, content, "\\0\\1use #{web}.UI\n", global: false)}

            true ->
              {:warning,
               "Could not find `import #{web}.CoreComponents` in #{web}. " <>
                 "Add `use #{web}.UI` to html_helpers/0 by hand."}
          end
        end)

      {:error, igniter} ->
        Igniter.add_warning(igniter, "Could not find #{web}; add `use #{web}.UI` by hand.")
    end
  end

  # Inside Phoenix's `if Application.compile_env(:app, :dev_routes)` scope, so
  # the gallery never ships to production.
  defp add_gallery_route(igniter, assigns) do
    router = assigns[:router]
    route = ~s|live "/ui", #{inspect(assigns[:web])}.UIGalleryLive|
    {igniter, present?} = Edits.source_contains?(igniter, router, "UIGalleryLive")

    if present? do
      igniter
    else
      Igniter.Project.Module.find_and_update_module!(igniter, router, fn zipper ->
        with {:ok, zipper} <-
               Igniter.Code.Function.move_to_function_call(
                 zipper,
                 :scope,
                 [2, 3],
                 &Igniter.Code.Function.argument_equals?(&1, 0, "/dev")
               ),
             {:ok, zipper} <- Igniter.Code.Common.move_to_do_block(zipper) do
          {:ok, Igniter.Code.Common.add_code(zipper, route)}
        else
          _ ->
            {:warning,
             "Could not find the dev-only `scope \"/dev\"` in #{inspect(router)}; " <>
               "add `#{route}` inside it by hand."}
        end
      end)
    end
  end

  defp create_list_state_test(igniter, assigns) do
    path = "test/#{assigns[:app]}_web/ui/list_state_test.exs"

    if Igniter.exists?(igniter, path) do
      igniter
    else
      Igniter.create_new_file(
        igniter,
        path,
        Gen.render_template("ui/list_state_test.exs.eex", assigns)
      )
    end
  end

  # -- layout ----------------------------------------------------------------

  # Phoenix's demo layout links to phoenixframework.org; anything else was
  # written by someone (or by an earlier run) and is left alone.
  defp replace_layout(igniter, assigns) do
    layouts = Module.concat(assigns[:web], "Layouts")
    stock? = &String.contains?(&1, "https://phoenixframework.org/")

    {igniter, customized?} =
      case Igniter.Project.Module.find_module(igniter, layouts) do
        {:ok, {igniter, source, _zipper}} ->
          content = Rewrite.Source.get(source, :content)
          {igniter, not stock?.(content) and not String.contains?(content, "app_shell")}

        {:error, igniter} ->
          {igniter, false}
      end

    igniter
    |> Gen.replace_module(layouts, Gen.render_template("ui/layouts.ex.eex", assigns), stock?)
    |> then(fn igniter ->
      if customized? do
        Igniter.add_notice(
          igniter,
          "#{inspect(layouts)} was customized, so it was left alone. Wrap its content in " <>
            "<.app_shell> (#{inspect(assigns[:web])}.UI.Shell) to use the themepack's shell."
        )
      else
        igniter
      end
    end)
  end
end
