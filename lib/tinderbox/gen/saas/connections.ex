defmodule Tinderbox.Gen.Saas.Connections do
  @moduledoc """
  OAuth2 client-credentials connections: how machines call the generated JSON:API.

  An organization's owners and admins create and revoke connections on the
  `/connections` page (`Tinderbox.Gen.Saas.Web`). The authorization server that
  holds the clients and issues the access tokens is pluggable like
  `<App>.Storage`: `OAUTH_PROVIDER` selects `hydra` (Ory Hydra, in
  `docker-compose.yml`, or hosted Ory Network) or `auth0`; both adapters are
  always generated.

  * `<App>.Connections` — the Ash domain and `active_by_client_id/1`, registered in
    `config :<app>, ash_domains`,
  * `<App>.Connections.Connection` — one row per client; the secret is never stored,
  * `<App>.Connections.Changes.RegisterClient` / `DeleteClient` — create and delete
    the client at the provider inside the `:create` and `:revoke` actions,
  * `<App>.Connections.Provider` — the behaviour and the `OAUTH_PROVIDER` switch,
    with the adapters `Providers.Hydra`, `Providers.Auth0` and `Providers.Fake`
    (the only one in `MIX_ENV=test`),
  * `<App>.Connections.Tokens` — verifies JWT access tokens against the issuer's
    JWKS (OIDC discovery), whatever the provider,
  * `<App>Web.Plugs.LoadConnection` — appended to the router's `:api` pipeline,
    after the user's bearer token had its chance: a valid token of an unrevoked
    connection becomes the Ash actor, an invalid one is answered with `401`,
  * runtime config (`OAUTH_*`, `HYDRA_*`, `AUTH0_*`) and a test of the API.

  The page, its route and navigation entry, the fixture and the page's test are
  generated by `Tinderbox.Gen.Saas.Web`; the organization's read policy that lets
  a connection read its own organization by `Tinderbox.Gen.Saas.Accounts`.
  """

  alias Tinderbox.Gen
  alias Tinderbox.Gen.Saas.Edits

  @spec apply(Igniter.t(), Tinderbox.Gen.Saas.assigns()) :: Igniter.t()
  def apply(igniter, assigns) do
    igniter
    |> create_modules(assigns)
    |> register_domain(assigns)
    |> add_runtime_config(assigns)
    |> add_plug(assigns)
    |> add_api_test(assigns)
  end

  defp create_modules(igniter, assigns) do
    connections = assigns[:connections]

    modules = [
      {connections, "connections.ex.eex"},
      {assigns[:connection], "connection.ex.eex"},
      {assigns[:provider], "provider.ex.eex"},
      {Module.concat([connections, "Providers", "Hydra"]), "providers/hydra.ex.eex"},
      {Module.concat([connections, "Providers", "Auth0"]), "providers/auth0.ex.eex"},
      {Module.concat([connections, "Providers", "Fake"]), "providers/fake.ex.eex"},
      {Module.concat(connections, "Tokens"), "tokens.ex.eex"},
      {Module.concat([connections, "Changes", "RegisterClient"]),
       "changes/register_client.ex.eex"},
      {Module.concat([connections, "Changes", "DeleteClient"]), "changes/delete_client.ex.eex"},
      {plug_module(assigns), "load_connection_plug.ex.eex"}
    ]

    Enum.reduce(modules, igniter, fn {module, template}, igniter ->
      Igniter.Project.Module.create_module(
        igniter,
        module,
        Gen.render_template("saas/connections/" <> template, assigns)
      )
    end)
  end

  defp register_domain(igniter, assigns) do
    connections = assigns[:connections]

    Igniter.Project.Config.configure(
      igniter,
      "config.exs",
      assigns[:app],
      [:ash_domains],
      [connections],
      updater: fn zipper -> Igniter.Code.List.prepend_new_to_list(zipper, connections) end
    )
  end

  defp add_runtime_config(igniter, assigns) do
    Gen.append_to_runtime_exs(
      igniter,
      Gen.render_template("saas/connections/runtime_config.exs.eex", assigns),
      fn igniter ->
        Igniter.Project.Config.configures_key?(igniter, "runtime.exs", assigns[:app], [
          :connections
        ])
      end
    )
  end

  # After `plug :set_actor, :user`: AshAuthentication has had its chance by then,
  # and the plug only looks at requests it left without a user.
  defp add_plug(igniter, assigns) do
    router = assigns[:router]
    code = "plug #{inspect(plug_module(assigns))}"
    {igniter, present?} = Edits.source_contains?(igniter, router, code)

    if present? do
      igniter
    else
      Igniter.Libs.Phoenix.append_to_pipeline(igniter, :api, code, router: router)
    end
  end

  defp add_api_test(igniter, assigns) do
    Igniter.create_new_file(
      igniter,
      "test/#{assigns[:app]}_web/api_connections_test.exs",
      Gen.render_template("saas/connections/api_connections_test.exs.eex", assigns)
    )
  end

  defp plug_module(assigns), do: Module.concat([assigns[:web], "Plugs", "LoadConnection"])
end
